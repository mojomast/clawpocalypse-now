// Rebuild convex alpha silhouettes used to settle downed bodies on the floor.
// No source PNGs are modified. Requires local HTTP server and npm ci.
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/snap/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.route('**/support-generator', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Support hull generator</title>' }));
  await page.goto((process.env.GAME_ORIGIN || 'http://127.0.0.1:48791') + '/support-generator');
  const hulls = await page.evaluate(async () => {
    const { HERO_RIGS } = await import('/hero-rigs.js');
    const result = {}, cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
    for (const [hero, parts] of Object.entries(HERO_RIGS)) {
      result[hero] = {};
      for (const [name, part] of Object.entries(parts)) {
        if (name.endsWith('_b') || name === 'weapon') continue;
        const image = new Image(); image.src = `/assets/heroes/${hero}/${part.file}`; await image.decode();
        const c = document.createElement('canvas'); c.width = image.width; c.height = image.height;
        const ctx = c.getContext('2d'); ctx.drawImage(image, 0, 0);
        const data = ctx.getImageData(0, 0, c.width, c.height).data, points = [];
        for (let x = 0; x < c.width; x++) for (let y = 0; y < c.height; y++) if (data[(y * c.width + x) * 4 + 3] >= 128) points.push([x + 0.5, y + 0.5]);
        const half = points => { const h = []; for (const p of points) { while (h.length >= 2 && cross(h.at(-2), h.at(-1), p) <= 0) h.pop(); h.push(p); } return h.slice(0, -1); };
        result[hero][name] = [...half(points), ...half([...points].reverse())];
      }
    }
    return result;
  });
  await writeFile(new URL('../hero-support.js', import.meta.url), '// Generated by tools/generate-support.mjs from unchanged PNG alpha (threshold 128).\nexport const HERO_SUPPORT = ' + JSON.stringify(hulls) + ';\n');
} finally { await browser.close(); }
