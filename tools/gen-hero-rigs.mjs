#!/usr/bin/env node
// Repo-local rig generator: assets/heroes/MANIFEST.md -> hero-rigs.js (export HERO_RIGS, HERO_V2).
//
//   node tools/gen-hero-rigs.mjs            writes ./hero-rigs.js
//   node tools/gen-hero-rigs.mjs --out DIR  writes DIR/hero-rigs.js instead (never touches the repo file)
//   node tools/gen-hero-rigs.mjs --check    exits 1 if ./hero-rigs.js differs from a fresh generation
//
// Port of pizza-panic-dev/tools/gen_enemy_rigs.mjs restricted to heroes and to this repo.
// v1 sections ("| part | image | size | pivot | parent | attach |") are emitted byte-for-byte as the
// old generator did, including the derived far limbs (same image, darkened, shoulder/hip nudged by
// ax-6, ay-2). Sections containing a "Rig: v2" line use the extended table written by
// tools/slice-hero-parts.py:
//   | part | image | size | pivot | parent | attach | role | data |
// where part may be "slot@variant", role is body|torso|hand|grip_front|weapon|foot|spring|variant,
// and data is space-separated key=v1,v2,... pairs (grip, axis, tip, grip2, sole, joint, spring,
// range, tint). v2 far limbs are listed explicitly; "_b" slots are drawn tinted unless tint=0.
// Per-hero v2 lines outside the table: "Layers: a, b, ..." (back to front) and "Wrist: c=.. hw=..".
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const arg = name => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : null; };
const check = process.argv.includes('--check');
const outDir = arg('--out') ? path.resolve(arg('--out')) : root;
const source = 'assets/heroes/MANIFEST.md';

export function parse(text) {
  const types = [];
  let current = null;
  for (const line of text.split('\n')) {
    const head = line.match(/^##\s+(\w+)\s+\((.+)\)/);
    if (head) { current = { kind: head[1], title: head[2], parts: [], moves: '', behavior: '', v2: false }; types.push(current); continue; }
    if (!current) continue;
    if (/^Rig:\s*v2\b/.test(line)) { current.v2 = true; continue; }
    const layers = line.match(/^Layers:\s*(.+)/);
    if (layers) { current.layers = layers[1].split(',').map(s => s.trim()).filter(Boolean); continue; }
    const wrist = line.match(/^Wrist:\s*c=(-?[\d.]+)\s+hw=([\d.]+)/);
    if (wrist) { current.wrist = { c: +wrist[1], hw: +wrist[2] }; continue; }
    const linksLine = line.match(/^Links:\s*(.+)/);
    if (linksLine) {
      current.links = {};
      for (const rule of linksLine[1].split(',').map(s => s.trim()).filter(Boolean)) {
        const [lhs, rhs] = rule.split('=').map(s => s.trim());
        if (!lhs || !rhs) continue;
        current.links[lhs] = Object.fromEntries(rhs.split('+').map(s => s.trim().split('@')));
      }
      continue;
    }
    const moveLine = line.match(/Mov[^:]*:\s*(.+)/);
    if (moveLine) current.moves = moveLine[1].trim();
    const grip = line.match(/^Weapon grip:\s*(-?\d+)/);
    if (grip) current.grip = +grip[1];
    const behave = line.match(/Behavior:\s*(.+)/);
    if (behave) current.behavior = behave[1].trim();
    if (current.v2) {
      const row = line.match(/^\|\s*([\w@]+)\s*\|\s*([\w.]+)\s*\|\s*(\d+)x(\d+)\s*\|\s*(-?\d+),(-?\d+)\s*\|\s*([\w-]+)\s*\|\s*(?:(-?\d+),(-?\d+)|-)\s*\|\s*(\w+)\s*\|\s*([^|]*)\|/);
      if (!row) continue;
      const [, part, image, w, h, px, py, parent, ax, ay, role, data] = row;
      const extra = {};
      for (const kv of data.trim().split(/\s+/).filter(Boolean)) {
        const [k, v] = kv.split('=');
        const nums = v.split(',').map(Number);
        extra[k] = nums.length === 1 ? nums[0] : nums;
      }
      current.parts.push({ part, image, w: +w, h: +h, px: +px, py: +py, parent: parent === '-' ? null : parent, ax: +(ax || 0), ay: +(ay || 0), role, extra });
      continue;
    }
    const row = line.match(/^\|\s*(\w+)\s*\|\s*([\w.]+)\s*\|\s*(\d+)x(\d+)\s*\|\s*(\d+),(\d+)\s*\|\s*([\w-]+)\s*\|\s*(?:(\d+),(\d+)|-)\s*\|/);
    if (!row) continue;
    const [, part, image, w, h, px, py, parent, ax, ay] = row;
    current.parts.push({ part, image, w: +w, h: +h, px: +px, py: +py, parent: parent === '-' ? null : parent, ax: +(ax || 0), ay: +(ay || 0) });
  }
  if (!types.length) throw new Error(`no types found in ${source}`);
  return types;
}

const js = v => JSON.stringify(v).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\S)/g, ', ').replace(/"/g, "'");

export function emit(types) {
  const out = [];
  out.push(`// GENERATED by tools/gen-hero-rigs.mjs from ${source}.`);
  out.push('// Do not hand-edit: re-run the generator after the art or manifest changes.');
  out.push('// Back limbs are not listed in the manifest, so they are derived here: the same');
  out.push("// image darkened with a small inward offset, matching MR.INDIA's convention.");
  out.push('');
  out.push('export const HERO_RIGS = {');
  const v2 = {};
  for (const t of types) {
    if (t.behavior) out.push(`  // ${t.title}: ${t.behavior}`);
    if (t.moves) out.push(`  // moves: ${t.moves}`);
    out.push(`  ${t.kind}: {`);
    if (t.v2) {
      const slots = {};
      for (const p of t.parts) {
        const [slot, variant] = p.part.split('@');
        const base = { file: p.image, w: p.w, h: p.h, px: p.px, py: p.py };
        for (const [k, v] of Object.entries(p.extra)) base[k] = v;
        if (variant) { (slots[slot] ||= { variants: {} }).variants ||= {}; slots[slot].variants[variant] = base; continue; }
        const entry = { ...base, parent: p.parent, ax: p.ax, ay: p.ay, role: p.role };
        if (p.role === 'weapon' && t.grip != null) entry.grip = t.grip;
        if (slot.endsWith('_b') && p.extra.tint !== 0) entry.back = true;
        delete entry.tint;
        slots[slot] = { ...entry, ...(slots[slot]?.variants ? { variants: slots[slot].variants } : {}) };
      }
      for (const [slot, e] of Object.entries(slots)) {
        if (!e.file) throw new Error(`${t.kind}: variant(s) of ${slot} without a default part`);
        const { variants, ...rest } = e;
        const tail = variants ? `, variants: ${js(variants)}` : '';
        out.push(`    ${slot}: ${js(rest).slice(0, -1)}${tail} },`);
      }
      v2[t.kind] = { layers: t.layers, wrist: t.wrist, ...(t.links ? { links: t.links } : {}) };
      if (!t.layers) throw new Error(`${t.kind}: v2 section needs a Layers: line`);
      for (const l of t.layers) if (!slots[l]) throw new Error(`${t.kind}: layer ${l} has no part row`);
    } else {
      for (const p of t.parts) {
        const parent = p.parent ? `'${p.parent}'` : 'null';
        const grip = p.part === 'weapon' && t.grip ? `, grip: ${t.grip}` : '';
        out.push(`    ${p.part}: { file: '${p.image}', w: ${p.w}, h: ${p.h}, px: ${p.px}, py: ${p.py}, parent: ${parent}, ax: ${p.ax}, ay: ${p.ay}${grip} },`);
      }
      for (const [back, front] of [['uarm_b', 'uarm'], ['farm_b', 'farm'], ['thigh_b', 'thigh'], ['shin_b', 'shin']]) {
        const f = t.parts.find(p => p.part === front);
        if (!f) continue;
        const parent = back.startsWith('uarm') ? 'torso' : back.startsWith('farm') ? 'uarm_b' : back.startsWith('thigh') ? 'torso' : 'thigh_b';
        const rootLimb = parent === 'torso';
        out.push(`    ${back}: { file: '${f.image}', w: ${f.w}, h: ${f.h}, px: ${f.px}, py: ${f.py}, parent: '${parent}', ax: ${rootLimb ? Math.max(2, f.ax - 6) : f.ax}, ay: ${rootLimb ? f.ay - 2 : f.ay}, back: true },`);
      }
    }
    out.push('  },');
  }
  out.push('};');
  out.push('');
  if (Object.keys(v2).length) {
    out.push('// v2 rigs (separate hands, feet, grips, variants and spring chains): draw order and wrist window.');
    out.push(`export const HERO_V2 = ${js(v2)};`);
  } else out.push('export const HERO_V2 = {};');
  out.push('');
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = emit(parse(fs.readFileSync(path.join(root, source), 'utf8')));
  if (check) {
    const live = fs.readFileSync(path.join(root, 'hero-rigs.js'), 'utf8');
    if (live !== text) { console.error('hero-rigs.js is out of date: run node tools/gen-hero-rigs.mjs'); process.exit(1); }
    console.log('hero-rigs.js matches assets/heroes/MANIFEST.md');
  } else {
    fs.mkdirSync(outDir, { recursive: true });
    fs.writeFileSync(path.join(outDir, 'hero-rigs.js'), text);
    console.log(`wrote ${path.join(outDir, 'hero-rigs.js')}`);
  }
}
