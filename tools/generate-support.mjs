// Rebuild convex alpha silhouettes used to settle downed bodies on the floor.
// No source PNGs are modified.
import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, extname } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp' };
let server = null, origin = process.env.GAME_ORIGIN;
if (!origin) {
  server = createServer(async (req, res) => {
    try {
      const path = resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
      if (!path.startsWith(root + '/')) throw Error('outside root');
      const data = await readFile(path);
      res.writeHead(200, { 'Content-Type': mime[extname(path)] || 'application/octet-stream' }); res.end(data);
    } catch { res.writeHead(404); res.end('not found'); }
  });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  origin = `http://127.0.0.1:${server.address().port}`;
}
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/snap/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.route('**/support-generator', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Support hull generator</title>' }));
  await page.goto(origin + '/support-generator');
  const hulls = await page.evaluate(async () => {
    const { HERO_RIGS, HERO_V2 = {} } = await import('/hero-rigs.js');
    const result = {}, cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
    for (const [hero, parts] of Object.entries(HERO_RIGS)) {
      result[hero] = {};
      const hullOf = async file => {
        const image = new Image(); image.src = `/assets/heroes/${hero}/${file}`; await image.decode();
        const c = document.createElement('canvas'); c.width = image.width; c.height = image.height;
        const ctx = c.getContext('2d'); ctx.drawImage(image, 0, 0);
        const data = ctx.getImageData(0, 0, c.width, c.height).data, points = [];
        for (let x = 0; x < c.width; x++) for (let y = 0; y < c.height; y++) if (data[(y * c.width + x) * 4 + 3] >= 128) points.push([x + 0.5, y + 0.5]);
        const half = points => { const h = []; for (const p of points) { while (h.length >= 2 && cross(h.at(-2), h.at(-1), p) <= 0) h.pop(); h.push(p); } return h.slice(0, -1); };
        return [...half(points), ...half([...points].reverse())];
      };
      for (const [name, part] of Object.entries(parts)) {
        // v2 rigs also get a weapon hull (rig.js keeps their weapons above the floor)
        if (!name.endsWith('_b') && !(name === 'weapon' && !HERO_V2[hero])) {
          result[hero][name] = await hullOf(part.file);
        }
        if (HERO_V2[hero] && part.variants) {
          for (const [vname, vpart] of Object.entries(part.variants)) {
            result[hero][`${name}@${vname}`] = await hullOf(vpart.file);
          }
        }
      }
    }
    return result;
  });
  await writeFile(new URL('../hero-support.js', import.meta.url), '// Generated by tools/generate-support.mjs from unchanged PNG alpha (threshold 128).\nexport const HERO_SUPPORT = ' + JSON.stringify(hulls) + ';\n');
} finally { await browser.close(); server?.close(); }
